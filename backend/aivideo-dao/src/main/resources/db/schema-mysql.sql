CREATE TABLE IF NOT EXISTS t_model_config (
    id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    model_code        VARCHAR(64)   NOT NULL COMMENT '模型编码，如 wan2.7-t2v',
    display_name      VARCHAR(64)   NOT NULL COMMENT '展示名称',
    provider          VARCHAR(32)   NOT NULL COMMENT '厂商：DASHSCOPE',
    mode              VARCHAR(8)    NOT NULL COMMENT 'T2V 文生视频 / I2V 图生视频',
    protocol          VARCHAR(32)   NOT NULL COMMENT '请求协议：WAN27_T2V / WAN27_I2V / WAN_LEGACY_I2V',
    resolutions       VARCHAR(64)   NOT NULL COMMENT '支持的分辨率，逗号分隔',
    ratios            VARCHAR(64)   NULL COMMENT '支持的画幅比例，逗号分隔（仅文生视频）',
    min_duration      INT           NOT NULL,
    max_duration      INT           NOT NULL,
    default_duration  INT           NOT NULL,
    price_480p        DECIMAL(10, 4) NULL COMMENT '元/秒',
    price_720p        DECIMAL(10, 4) NULL COMMENT '元/秒',
    price_1080p       DECIMAL(10, 4) NULL COMMENT '元/秒',
    supports_audio    TINYINT       NOT NULL DEFAULT 0,
    description       VARCHAR(255)  NULL,
    price_note        VARCHAR(255)  NULL COMMENT '价格说明',
    enabled           TINYINT       NOT NULL DEFAULT 1,
    sort_order        INT           NOT NULL DEFAULT 0,
    created_at        DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_model_code (model_code)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '视频模型配置与单价';

CREATE TABLE IF NOT EXISTS t_video_task (
    id                      BIGINT AUTO_INCREMENT PRIMARY KEY,
    provider                VARCHAR(32)    NOT NULL COMMENT '实际调用的厂商：DASHSCOPE / MOCK',
    model_code              VARCHAR(64)    NOT NULL,
    mode                    VARCHAR(8)     NOT NULL,
    status                  VARCHAR(16)    NOT NULL COMMENT 'SUBMITTING/PENDING/RUNNING/SUCCEEDED/FAILED/CANCELED/TIMEOUT',
    prompt                  VARCHAR(5000)  NULL COMMENT '用户原始提示词',
    final_prompt            TEXT           NULL COMMENT '实际提交给模型的提示词（千问润色后）',
    negative_prompt         VARCHAR(500)   NULL,
    image_url               VARCHAR(1024)  NULL COMMENT '首帧图片',
    resolution              VARCHAR(8)     NOT NULL,
    ratio                   VARCHAR(8)     NULL,
    duration                INT            NOT NULL COMMENT '请求时长（秒）',
    enhance_prompt          TINYINT        NOT NULL DEFAULT 0,
    prompt_extend           TINYINT        NOT NULL DEFAULT 1,
    watermark               TINYINT        NOT NULL DEFAULT 0,
    audio                   TINYINT        NULL,
    seed                    BIGINT         NULL,
    provider_task_id        VARCHAR(128)   NULL,
    remote_video_url        VARCHAR(2048)  NULL COMMENT '厂商返回地址（24 小时有效）',
    local_video_path        VARCHAR(512)   NULL COMMENT '本地保存路径',
    error_code              VARCHAR(64)    NULL,
    error_message           VARCHAR(1024)  NULL,
    billed_duration         INT            NULL COMMENT '计费时长（秒）',
    unit_price              DECIMAL(10, 4) NULL COMMENT '视频单价 元/秒',
    video_cost              DECIMAL(12, 4) NOT NULL DEFAULT 0 COMMENT '视频生成费用（元）',
    llm_input_tokens        INT            NOT NULL DEFAULT 0,
    llm_output_tokens       INT            NOT NULL DEFAULT 0,
    llm_cost                DECIMAL(12, 6) NOT NULL DEFAULT 0 COMMENT '提示词润色费用（元）',
    total_cost              DECIMAL(12, 4) NOT NULL DEFAULT 0 COMMENT '总费用（元）',
    enhance_ms              BIGINT         NULL COMMENT '提示词润色耗时',
    queue_ms                BIGINT         NULL COMMENT '厂商排队耗时',
    generate_ms             BIGINT         NULL COMMENT '厂商生成耗时',
    total_elapsed_ms        BIGINT         NULL COMMENT '从创建到完成的总耗时',
    provider_submit_time    DATETIME(3)    NULL,
    provider_scheduled_time DATETIME(3)    NULL,
    provider_end_time       DATETIME(3)    NULL,
    finished_at             DATETIME(3)    NULL,
    created_at              DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at              DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    KEY idx_video_task_status (status),
    KEY idx_video_task_created (created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '视频生成任务（含耗时与费用统计）';
